ap = argparse.ArgumentParser()
ap.add_argument("--only", type=int, nargs="+", help="FAQ ids to add aliases to")
ap.add_argument("--all", action="store_true")
ap.add_argument("--clear", action="store_true")
args = ap.parse_args()
if not (args.only or args.all or args.clear):
    sys.exit("Choose one: --only ID [ID ...]  |  --clear  |  --all")

path = Path(DATA_PATH)
faqs = json.loads(path.read_text(encoding="utf-8"))


def save():
    path.write_text("[\n" + ",\n".join(json.dumps(f, ensure_ascii=False) for f in faqs) + "\n]\n", encoding="utf-8")


if args.clear:
    n = sum(1 for f in faqs if f.pop("aliases", None) is not None)
    save()
    sys.exit(print(f"removed aliases from {n} FAQs. Total FAQs: {len(faqs)}"))

ids = set(ALIASES) if args.all else set(args.only)
test_set = {normalize(t) for f in faqs for t, _ in f.get("q", [])}
added = 0
for f in faqs:
    if f["id"] not in ids:
        continue
    new = [a for a in ALIASES.get(f["id"], []) if normalize(a) not in test_set and normalize(a) != normalize(f["question"])]
    if new:
        f["aliases"] = new
        added += 1
save()
print(f"aliases added to {added} FAQs (ids: {sorted(ids)[:10]}{'...' if len(ids) > 10 else ''}). Total FAQs: {len(faqs)}")
